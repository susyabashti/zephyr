#!/usr/bin/env python3
"""Generate the frozen combining-mark range table (spec section 4.1).

Writes:
  spec/data/mark_ranges.txt  human-readable merged ranges
  src/core/mark_ranges.zig   Zig array literal consumed by src/core/nfc.zig

The table lists every codepoint whose Unicode general category is Mn
(nonspacing mark), Mc (spacing mark), or Me (enclosing mark). The v1 writer
rejects text or tags containing any of these codepoints; everything else is
stored byte-for-byte as given (frozen strict subset of UAX #15 NFC).
"""
import unicodedata


def merged_ranges(cps):
    ranges = []
    start = prev = cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev))
            start = prev = cp
    ranges.append((start, prev))
    return ranges


def main():
    marks = [cp for cp in range(0x110000)
             if unicodedata.category(chr(cp)) in ("Mn", "Mc", "Me")]
    ranges = merged_ranges(marks)

    with open("spec/data/mark_ranges.txt", "w") as f:
        f.write("# Unicode combining marks (categories Mn, Mc, Me), merged ranges.\n")
        f.write("# Generated by test/generate_mark_ranges.py. Do not edit by hand.\n")
        for lo, hi in ranges:
            f.write(f"0x{lo:04X} 0x{hi:04X}\n")

    with open("src/core/mark_ranges.zig", "w") as f:
        f.write("//! Frozen combining-mark ranges (spec section 4.1).\n")
        f.write("//! Generated by test/generate_mark_ranges.py. Do not edit by hand.\n\n")
        f.write("pub const ranges: []const struct {\n    lo: u21,\n    hi: u21,\n} = &.{\n")
        for lo, hi in ranges:
            f.write(f"    .{{ .lo = 0x{lo:04X}, .hi = 0x{hi:04X} }},\n")
        f.write("};\n")

    print(f"wrote {len(ranges)} ranges covering {len(marks)} codepoints")


if __name__ == "__main__":
    main()
